type osaOutcome struct {
	Family          string   `json:"family"`
	Outcome         string   `json:"outcome"`
	Fault           string   `json:"fault"`
	InvalidProperty string   `json:"invalidProperty"`
	Entities        int      `json:"entities"`
	Labels          []string `json:"labels"`
}
type csvEnvelope struct {
	Body struct {
		Response struct {
			Values []struct {
				Ref     string `xml:"entityRefId"`
				Samples string `xml:"sampleInfo"`
				Series  []struct {
					Metric struct {
						Label    string `xml:"label"`
						Interval int    `xml:"metricsCollectInterval"`
					} `xml:"metricId"`
					Values string `xml:"values"`
				} `xml:"value"`
			} `xml:"returnval"`
		} `xml:"VsanPerfQueryPerfResponse"`
	} `xml:"Body"`
}

// The oracle is extracted from all wildcard responses in the sanitized OSA
// primary-online walk, independently of the embedded synthetic-value catalog.
func TestOSAOnlineOutcomesMatchSanitizedWalk(t *testing.T) {
	raw, err := os.ReadFile("testdata/osa-perf-outcomes.json")
	if err != nil {
		t.Fatal(err)
	}
	var cases []osaOutcome
	if err := json.Unmarshal(raw, &cases); err != nil {
		t.Fatal(err)
	}
	sc := scenario.Phase1("osa-outcomes")
	sc.Defaults.Architecture = "osa"
	sc.Defaults.Hosts = 3
	sc.Defaults.Host.Threads = 5
	sc.Defaults.Host.DomWorlds = scenario.IntPtr(14)
	sc.Defaults.Host.VsanPnics = 1
	e := startWith(t, topology.Generate(sc, registry.InMemory(sc.Seed)), sim.Options{})
	if err := e.login("administrator@vsphere.local", "VMware1!"); err != nil {
		t.Fatal(err)
	}
	counts := map[string]int{}
	for _, tc := range cases {
		t.Run(tc.Family, func(t *testing.T) {
			counts[tc.Outcome]++
			status, body := e.postPerf(e.cl().Ref, tc.Family)
			got := parseShape(t, body)
			switch tc.Outcome {
			case "fault":
				if status != 500 || got.fault != tc.Fault+"Fault" || tc.InvalidProperty != "" && got.text["invalidProperty"] != tc.InvalidProperty {
					t.Fatalf("fault status=%d type=%q property=%q", status, got.fault, got.text["invalidProperty"])
				}
			case "empty":
				if status != 200 || len(got.refs) != 1 || got.refs[0] != tc.Family+":*" || len(got.labels) != 0 {
					t.Fatalf("empty status=%d refs=%v labels=%d", status, got.refs, len(got.labels))
				}
			case "samples":
				if status != 200 {
					t.Fatalf("status=%d body=%s", status, body)
				}
				var env csvEnvelope
				if err := xml.Unmarshal(body, &env); err != nil {
					t.Fatal(err)
				}
				entities := env.Body.Response.Values
				if len(entities) != tc.Entities {
					t.Fatalf("entities=%d want %d", len(entities), tc.Entities)
				}
				for _, entity := range entities {
					if !strings.HasPrefix(entity.Ref, tc.Family+":") || strings.HasSuffix(entity.Ref, ":*") {
						t.Errorf("invalid entity ref %q", entity.Ref)
					}
					// The walk distinguishes per-core, per-world and NIC subobjects
					// by suffix; the UUID portions are generated by the simulator.
					for family, suffix := range map[string]string{
						"host-cpu": "|cpu-", "dom-world-cpu": "|VSAN_0x", "lsom-world-cpu": "|PLOG-",
						"vsan-pnic-net": "|vmnic", "vsan-vnic-net": "|defaultTcpipStack|vmk",
						"vsan-tcpip-stats": "|defaultTcpipStack", "vnic-rdt-network-latency": "|vmk",
					} {
						if tc.Family == family && !strings.Contains(entity.Ref, suffix) {
							t.Errorf("%s: missing captured suffix pattern %q", entity.Ref, suffix)
						}
					}
					stamps := strings.Split(entity.Samples, ",")
					if len(stamps) != 4 {
						t.Errorf("%s: sample count %d", entity.Ref, len(stamps))
					}
					labels := make([]string, 0, len(entity.Series))
					for _, series := range entity.Series {
						labels = append(labels, series.Metric.Label)
						if series.Metric.Interval != 300 || len(strings.Split(series.Values, ",")) != len(stamps) {
							t.Errorf("%s %s: interval=%d values=%q", entity.Ref, series.Metric.Label, series.Metric.Interval, series.Values)
						}
					}
					if !reflect.DeepEqual(labels, tc.Labels) {
						t.Errorf("%s: metric label order differs from sanitized capture", entity.Ref)
					}
				}
			default:
				t.Fatalf("unknown outcome %q", tc.Outcome)
			}
		})
	}
	if len(cases) != 74 || counts["samples"] != 30 || counts["empty"] != 26 || counts["fault"] != 18 {
		t.Fatalf("unexpected captured outcome counts: %d %v", len(cases), counts)
	}
}
